#!/usr/bin/env python3
"""Generate release-notes.mdx from the YourSSH CHANGELOG.md.

Usage: gen_release_notes.py CHANGELOG.md release-notes.mdx [--since 0.2.0]

Each "## [x.y.z] — date" section becomes a Mintlify <Update> block. Text
outside code spans/fences is escaped for MDX ({ } < become literals), so
CHANGELOG prose can never break the docs build. Sections before --since are
left out (the early 0.1.x entries are development notes).
"""
import re
import sys

HEAD = re.compile(r"^## \[(\d+\.\d+\.\d+)\]\s*[—-]\s*(\d{4}-\d{2}-\d{2})\s*$")


def ver(v):
    return tuple(int(x) for x in v.split("."))


def escape_line(line):
    # Escape MDX-significant characters outside inline code spans.
    parts = re.split(r"(`+[^`]*`+)", line)
    out = []
    for i, p in enumerate(parts):
        if i % 2 == 1:
            out.append(p)
        else:
            out.append(p.replace("{", "\\{").replace("}", "\\}").replace("<", "&lt;"))
    return "".join(out)


def convert(text, since):
    sections, cur = [], None
    for line in text.splitlines():
        m = HEAD.match(line)
        if m:
            cur = {"version": m.group(1), "date": m.group(2), "lines": []}
            sections.append(cur)
            continue
        if line.startswith("## "):  # [Unreleased] or anything else ends a section
            cur = None
            continue
        if cur is not None:
            cur["lines"].append(line)
    sections = [s for s in sections if ver(s["version"]) >= ver(since)]
    body = []
    for s in sections:
        lines = s["lines"]
        while lines and lines[-1].strip() in ("", "---"):
            lines.pop()
        while lines and not lines[0].strip():
            lines.pop(0)
        fenced = False
        conv = []
        for l in lines:
            if l.lstrip().startswith("```"):
                fenced = not fenced
                conv.append(l)
                continue
            conv.append(l if fenced else escape_line(l))
        body.append(
            f'<Update label="v{s["version"]}" description="{s["date"]}">\n\n'
            + "\n".join(conv)
            + "\n\n</Update>\n"
        )
    header = (
        "---\n"
        'title: "Release notes"\n'
        'description: "What changed in each YourSSH release."\n'
        'icon: "newspaper"\n'
        "---\n\n"
        "{/* Generated by scripts/gen_release_notes.py from the YourSSH CHANGELOG.md at the latest release. Do not edit by hand. */}\n\n"
        "Download any release from the [releases page](https://github.com/YoursshLabs/yourssh/releases). "
        "The full history, including early development builds, is in [CHANGELOG.md](https://github.com/YoursshLabs/yourssh/blob/master/CHANGELOG.md).\n\n"
    )
    return header + "\n".join(body)


def main():
    args = sys.argv[1:]
    since = "0.2.0"
    if "--since" in args:
        i = args.index("--since")
        since = args[i + 1]
        del args[i : i + 2]
    src, dst = args
    with open(src, encoding="utf-8") as f:
        out = convert(f.read(), since)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(out)


if __name__ == "__main__":
    main()
